"""
Query生成的提示词模板
用于根据工具环境生成多样化的查询
"""
import json
from typing import Dict, List, Any
from ..utils.tool_loader import load_tool_schemas_from_yaml


def get_query_generate_prompt() -> str:
    """
    获取query生成的提示词模板
    
    Returns:
        str: 提示词模板字符串，包含{tools_json}和{num_queries}占位符
    """
    return '''你是一个专业的金融查询生成专家。现在需要你根据给定的工具环境，生成一批高质量、多样化的金融相关查询。

可用工具详细信息：
{tools_json}

## 生成要求

### 1. 多样性要求
生成的查询必须在以下维度具有高度多样性：
- **查询类型**：行业研究、事件解读、个股分析、宏观分析、股票检索等
- **复杂度**：简单查询（单工具）、中等复杂度（2-3个工具）、高复杂度（多工具多步骤）
- **领域覆盖**：不同行业板块、不同市场主题、不同投资策略
- **条件组合**：明确指标、模糊条件、时间限制、多条件组合等

### 2. 可解决性要求
每个查询都必须能够通过调用上述工具来解决：
- 确保查询所需的信息能够通过工具获取
- 查询的条件和要求在工具能力范围内
- 不要生成需要工具能力之外信息的查询

### 3. 质量要求
- 查询表达清晰、具体，符合真实用户的提问习惯
- 查询具有实际价值，是用户真实可能问的问题
- 避免过于宽泛或过于狭窄的查询
- 保持金融专业性和准确性

### 4. 查询类型示例

#### 类型1：基于明确指标的选股查询
- "推荐几只市盈率低于15，ROE大于15%的科技股"
- "筛选市值在100-500亿之间，近一年净利润增长率超过30%的医药股"

#### 类型2：基于热点主题的查询
- "最近人工智能板块有哪些潜力股，要求基本面良好"
- "新能源汽车产业链上有哪些值得关注的上游公司"

#### 类型3：基于模糊条件的查询
- "推荐几只化工板块的高成长性股票"
- "找一些具有投资价值的周期股"

#### 类型4：信息查询类
- "比亚迪最近的基本面情况如何"
- "半导体行业的最新发展趋势是什么"

#### 类型5：综合分析类
- "在消费电子领域，哪些公司既有技术优势又有良好的财务表现"
- "结合当前经济形势，推荐适合防御性投资的板块和个股"

### 5. 复杂度分布建议
- 简单查询（30%）：单一条件或单一主题
- 中等复杂度（50%）：2-3个条件组合或需要多步分析
- 高复杂度（20%）：多条件、多维度、需要深度分析

请生成 {num_queries} 个符合上述要求的查询。确保这些查询：
1. 在主题、复杂度、查询类型上分布均匀
2. 都能通过给定的工具环境来解决
3. 表达自然、具有实际应用价值
4. 避免重复或相似的查询

请严格按照以下JSON格式输出：

{{
  "queries": [
    {{
      "content": "查询的具体内容文本",
      "complexity_level": "复杂度级别(simple/medium/high之一)",
      "query_type": "查询类型(如：选股推荐、信息查询、数据分析、行业研究等)",
      "expected_tools": ["预期使用的工具名称1", "工具名称2"]
    }},
    ...
  ]
}}

注意：
- "content": 查询的完整文本内容
- "complexity_level": 必须是 "simple"、"medium" 或 "high" 之一
- "query_type": 描述查询的主要类型
- "expected_tools": 列出完成该查询预期需要调用的工具名称列表
'''


def format_tools_for_prompt(tools_info: List[Dict[str, Any]]) -> str:
    """
    将工具信息格式化为适合prompt的字符串
    
    Args:
        tools_info: 工具信息列表
        
    Returns:
        格式化后的工具信息字符串
    """
    return json.dumps(tools_info, ensure_ascii=False, indent=2)

