"""
Reviser 第一阶段（扩展任务）prompt 构造器。

第一阶段目标：
- 基于 trajectory 扩展任务流程图；
- 基于新流程图生成复杂度驱动的 query；
- 输出流程图文本字段、`query`，并为每个节点输出“源头溯源”信息。
"""

from __future__ import annotations

import json
from typing import Any, Dict, Optional


def build_revise_expand_task_prompt(
    *,
    mermaid_k: Optional[str],
    traj_k: Dict[str, Any],
    metadata: Optional[Dict[str, Any]] = None,
) -> str:
    metadata = metadata or {}
    traj_k_str = json.dumps(traj_k, ensure_ascii=False, indent=2)
    metadata_str = json.dumps(metadata, ensure_ascii=False, indent=2)
    mermaid_block = (mermaid_k or "").strip()
    if mermaid_block:
        mermaid_section = f"""- 上一轮 mermaid：
    ```mermaid
    {mermaid_block}
    ```"""
    else:
        mermaid_section = "- 上一轮 mermaid：（空，本轮需从 trajectory 新建）"

    prompt = f"""你是一个根据trajectory，以扩展deep research任务搜索范围和深度，以构造更有价值的任务助手。你需要返回一个流程图mermaid、`query` 和 `rubric`。其中：
    - `mermaid` 用来建模任务；
    - `query` 对扩展后任务进行引导式提问；
    - `rubric` 是该任务的可判定评估标准（用于后续评估）。

## 已知信息

{mermaid_section}

- 工具调用轨迹（trajectory）的结构化表示（原样展示其结构和主要内容）：
{traj_k_str}



# 你的工作流程
1. 如果mermaid为空，先从 trajectory 中得到关键节点及逻辑关系，并生成一个符合上述要求的 mermaid；不为空则跳过该步骤，直接根据已有的mermaid执行下一步修改、扩充mermaid。

2. 修改mermaid。根据trajectory中的user问题部分，删除已有mermaid里有，但是与该task无关的旁枝节点，只保留完成该task所需要的充分且最少节点。然后重新组织mermaid，使得mermaid的节点和逻辑更加合理和清晰。

3. 扩展mermaid。分析trajectory中有，但是mermaid里没有被写入到的信息（在上一步中被删除的节点信息不要重复添加），扩展生成更复杂的mermaid：
  - 优先深度扩展：即在主链路上，使得整个task在深度上变难，即解决所需要经过的路径变长。在纵向扩展时，优先考虑往后或者往前延伸，而不是添加中间节点。深度扩展的后的task可能与扩展前的task不一致，聚焦于“小步深挖”一个在trajectory中提到，但是mermaid没有深入的信息，可以改变当前mermaid的整体task，或者已有节点，以实现更复杂的任务，但是禁止全图级全部大改。如果改变了整体task，根据扩展后的task调整mermaid，修改已有节点和逻辑，以保证整个任务的逻辑合理性和一致性。在深度上增加的节点最多2个。
  - 横向扩展：围绕其中的某个节点，进行trajectory涉及到，但是mermaid中没有的信息补充，横向扩展一般不会改变task，可以一次性扩展0-10个节点。
  - 禁止无意义扩展，所有新增节点都必须带来增量信息。若无高价值新增信息，允许 0 增量或者仅修改已有节点。禁止添加无意义的节点，比如重复语义节点（同义改写算重复），或者只把同一事实问题换措辞后重复核（“再次检索同一事实”，“更换渠道验证消息有效性”）的节点。
  - **扩展原则**：
    - 扩展的节点信息必须完全来源于trajectory中的信息，不能编造信息，新增节点保持与之前mermaid中已有节点的关联性。
    - 每轮扩展结束时，检查扩展后的mermaid，应当符合对mermaid的格式和内容要求，如果不符合进行修复。

4. 基于扩充后的流程图生成新的 `query`：
  - query是对mermaid的整体任务的提问，需要涉及到mermaid中所有关键约束，不要降低内在推理路径的复杂度。同时，引导agent去做该mermaid提到（必须是已有节点，而不是凭空造任务），但还没有深入探索的任务，目的是生成更有难度的task，且希望该task是具体的，合理的，有意义的。包括但不限于：
    - 让agent解释/验证/深入某个节点
    - 让agent结合几个节点进行综合分析/推理/对比
  - query 必须是单任务表达：每一轮只选择一个最有潜力的方向继续演化，不得并行发展多个独立问题，也不要同时询问多个问题。可以包含多个方面约束，但不能变成多个互相独立的问题集合。
  - **query必须是一个task的完整描述（硬性）**：该query是独立于mermaid和trajectory的，因此 query 里禁止使用“基于已输出/如上/上述/前文/上一轮/终版/继续上次”等指代性表述。若一定需要复用历史信息，把必要事实直接写进 query 本身（用简洁事实重述），确保仅凭这条 query 就能执行。
  - **query可执行性约束（硬性）**：
    - 只保留 1 个主目标 + 最多 10 条关键约束，禁止无限叠加需求导致“超长但不可执行”。
    - 不要在 query 中预设具体结论（如指定某店必须高风险）或预设固定分数/阈值（如“2.4分”“>8分”）。
    - **禁止设计类问法（硬性）**：不要把目标写成“设计方法论/设计系统/设计机制/构建框架/输出手册”之类产物导向任务。
    - query 应优先是“事实性分析问题”：围绕核验、比较、归因、趋势判断来提问，并要求结论必须由可核对证据支撑。

5. 基于扩充后的 `mermaid` + `query` 设计节点级 rubric criterion（写入 `node_sources`）：
  - 不单独输出顶层 `rubric` 字段，系统会在后处理阶段根据 `node_sources` 自动组装。
  - 每个节点必须绑定一个唯一 criterion（节点与 criterion 一一对应）。
  - criterion 字段与约束：
    - `id` (string): 3-64 字符，仅小写字母/数字/下划线。
    - `description` (string): 人类可读，明确该项判定目标与逻辑。
    - `check_points` (string[]): 非空；每条必须可机械判定，避免“全面/深入/高质量”等主观词。内容需要具体，来源于已知的信息，不要编造证据，且必须是可验证的。


## mermaid的要求
- 总体要求：mermaid必须是 flowchart 语法的 DAG（不能出现回边/循环边）。是对trajectory的内部信息搜集/推理流程，基于给你的 mermaid（可能为空） + trajectory 得到节点内容及逻辑关系，不要凭空捏造。

- 节点内容：节点是内容必须是 trajectory 中存在的**具体行为，对象和结果**，统一设计为[(类型) 行为+对象：结果]的格式。**严格**根据使用trajectory中的信息是否可以被直接验证分为两类：
  - 事实性节点：有明确来源或证据，不依赖逻辑推导即可成立的，基于搜索得到的事实性信息。只有tool_response里的信息可以变成事实性节点。举例：使用google搜索北京天气的tool_call以及返回的页面内容，在变成事实性节点时，至少需要包括其节点类型，具体的搜索对象是谁，搜索结果，即[(事实性) 搜索北京天气：晴天]。
  - 推理性节点：不是直接来源中的信息，而是基于信息进行分析（因果、归纳、比较、预测等）得到的信息，但依旧必须来源于trajectory。举例：模型reasoning过程中计算股票估值的信息，至少需要包括其节点类型，具体的计算对象，计算结果，即[(推理性) 计算得到紫金矿业估值价格：32元]。

- 节点粒度：无论是事实性节点还是推理性节点，一个节点最多对应单个操作，比如一次工具调用搜索的一个对象，或者针对一个问题的推理分析，不要把多个操作揉在一起。节点数目没有限制，尽量完备，不编造，不遗漏。

- **失败节点禁入（硬性）**：
  - 任何“未获取到有效信息”的结果都不得成为节点，包括但不限于：请求失败、抓取失败、动态占位符未渲染、空结果、被反爬拦截、超时等。
  - 这类失败信息只能用于你内部判断“某来源不可用”，不能写成 `node_text`，也不能单独分配 rubric criterion。
  - 例如类似“抓取新浪页面失败/返回@now@占位符”的内容，禁止作为 mermaid 节点输出。

- **元节点禁入（硬性）**：
  - 禁止在最终节点中出现“流程编排/元认知”语义，例如：`识别信息缺口`、`深化方向`、`规划下一步`、`生成扩展任务`、`构建任务框架`、`输出终版`、`闭环操作手册` 等。
  - 允许你在内部先做“缺口识别/深化方向选择”来决定mermaid的扩展策略，但这类内容只用于内部推理，不能作为节点内容输出。若内部确实做了缺口识别，必须转译为任务域节点再输出（如“核验某店2026营业状态”“比对近3个月口碑标签”），而非输出“识别缺口”本身。
  - 节点内容只能使用本轮 tool_response、query、上一轮 mermaid 中已出现且可对齐的概念，不允许新增未出现的主题维度或新术语，尽量使用已有内容中的词汇，切忌为了深度故意使用有难度的术语。
  - `node_text` 必须是可执行求解动作或可验证分析结论，不能描述“如何继续思考/如何改写query”。
  - 禁止没有上游节点支撑的明确答案的节点，比如“设计方法论/构建系统/设计机制/形成手册/搭建框架”等抽象产物节点。

- 边的走向要求：能反映实际的信息和信息流，可以有多个起点或者终点。通过判断节点和与其相关的节点的逻辑关系，然后进行对应的关系组织。
  - 推导关系对应节点间的纵向组织：后续节点直接用到前序节点的信息。只有后续节点确定是由前序节点推导而来（没有前序节点无法链接至后续节点的情况）才能进行纵向组织，否则是并列关系：
    - 比如节点[(事实性) 查询股东户数变化：获取截至2026-03-31股东户数125.2万及较上期增长情况]"的前提是要知道是哪只股票，所以可以通过"[(事实性) 查询股票名称：紫金矿业]->[(事实性) 查询股东户数变化：获取截至2026-03-31股东户数125.2万及较上期增长情况]"进行纵向组织。
  - 互补（并列）关系对应节点间的横向组织：并列节点代表了解决同一个任务的不同考虑方面，即使操作对象是同一个，但可以不依赖彼此独立完成。

- **边的连通性与完整性（硬性要求，输出前必须满足）**：
  - 禁止悬空节点：图中每个节点都必须至少出现在一条边中（有入边或出边）；禁止只定义节点、不写任何 `A --> B`。
  - 禁止无依据的推理性节点：每个**推理性**节点必须至少有 1 条入边，且入边来源必须是其推理所依赖的事实/前序推理节点；禁止出现“没有任何上游、却直接连到终点”的推理性节点。
  - 禁止中间死胡同：除“仅做信息采集、不再被下游使用”的**事实性叶子节点**外，其余节点若写了结果且会被后续分析使用，必须有至少 1 条出边指向实际消费该结果的下游节点。
  - 边与 node_sources 一致：你在 `node_sources.source_note` 里写明的依据节点，必须在 mermaid 中存在对应的数据流路径（可直接 `X --> Y`，或经中间节点 `X --> ... --> Y`）。若 note 写“基于 A/B/C”，则 A、B、C 都必须能到达该节点。
  - 扩展现有图时优先修边：继承上一轮节点后，若发现已有节点入边/出边缺失、与 source_note 不符，分析节点未汇入综合结论、推理性节点缺入边等问题，应首先修改补全mermaid，而不是只堆新节点。每新增一个节点，必须同时写出它与上下游的边；禁止只加节点、不改连通关系。

## 节点源头（必须输出）
你必须为 mermaid 中**每一个节点**输出一条溯源记录，放在 `node_sources` 字段中。要求如下：
- `node_id`：节点ID（如 A/B/C...），必须和 mermaid 中一致。
- `node_text`：节点完整文本（即节点方括号里的内容）。
- `rubric_criterion`：该节点唯一对应的 criterion 对象（object）。
  - 字段必须包含：`id`、`description`、`check_points`。
  - **一对一硬性约束**：每个节点必须且只能对应一个 criterion；不同节点禁止使用同一个 criterion id。
  - 该字段用于表达“节点 -> 评估标准”的映射，必须可解释：为什么这个节点支撑该 criterion。
- `source_type`：节点信息来源类型，只能取以下之一：
  - `tool_call_response`：来自本轮 trajectory 的工具调用及返回。
  - `query_or_reason_or_answer`：来自 query/reason/final answer。
  - `previous_mermaid`：来自上一轮 mermaid 的继承节点（本轮 traj 未新增证据）。
- `source_note`：来源+证据的合成描述（简短字符串，不超过120字，必须可在输入中定位且不可编造）：
  - 若 `tool_call_response`，写 `tool_call_id=<id>` 并附工具名/关键词与关键证据。
  - 若 `query_or_reason_or_answer`，写明片段位置（如 `query` / `reason` / `final_answer`）并附关键证据。
  - 若 `previous_mermaid`，写 `from_previous_mermaid` 并附继承依据。
- 当 `source_type=query_or_reason_or_answer` 时，不得新增 `tool_response` 中不存在的命名实体、缩写或数值规则。不得进行“术语升级”（把证据里的普通描述改写为更专业但未出现的术语，如把“具体步骤”改成“SOP”）。

## 注意


- 实事求是是第一原则，整个过程中，严禁添加任何编造的节点或者信息，也不要为了深度和专业刻意进行包装： 
  - 无论是query，还是mermaid中，禁止引入任何没有明确规定，大众普遍认知的，新命名术语（如自造模型名、缩写、评分体系名、方法学名），也不要从trajectory里的回答中引入ai命名的带引号的不明确的形容词（如“讽刺感丧失”，“贫瘠感”，“神话式历史主义”等）。如果有大众普遍认知的术语，则必须来自以下集合之一：`tool_response` 原文、上一轮 mermaid 原文，禁止输出任何不在集合内的新命名。若仅能从 `query/reason/final_answer` 归纳，请使用通用表述（如“多维风险评估”），不要创造新专有名词。
  - 同样的，禁止输出未经过标准方法验证过（也就是可以通过查询或者搜索得到）的计算推理方法，数值、计算公式或分级阈值。
  - 术语贴源：`node_text`，`query`中出现的关键词（尤其方法名、机制名、缩写）必须能在对应 `source_note` 指向的证据片段中找到；找不到就改写为朴素描述，**禁止术语包装（硬性）**，不得把证据中的普通词替换为更“专业”的新词（如把“对比”包装成“耦合分析”，把“判断真假”包装成“真伪判别模型”）


- 输出前自检：
  - 再次检查所有节点内容，格式和粒度，确保节点内容具体，符合格式。尤其是推导关系的节点是不是严格符合“后序节点的前提是前序节点”的定义，可以独立完成的两个任务应该被定义为并列关系。
  - 如果 query 中出现“基于已输出/上述/前文/上一轮/继续上次/终版”等词，必须重写为自包含版本。
  - 如果 query 仍在重复确认同一事实（只是换来源/换问法），没有升级到“原因/影响/比较/演化”层级，必须重写。
  - 如果 query 出现“固定分值/固定阈值/自造缩写体系/预设结论/单句极长清单式堆砌”，必须重写为可验证、可执行版本。
  - 如果 node_text/query 使用了证据中未出现（或者没有被广泛定义并承认过）的“专业术语包装词”（如 SOP、博弈、对冲、闭环机制，或者带引号的词汇），必须替换为证据同义的朴素表达。
  - 如果 query/node_text 出现“设计方法论/设计系统/设计机制/构建框架/执行手册”等产物导向表述，必须改写为事实核验与分析导向表述。
  - 如果出现无法在证据中定位来源的术语，必须删除该术语并用朴素描述重写，宁可变得直白也不要为了深度刻意“显得专业”。

## 输出形态
你最终的输出会被解析为一个严格的 JSON 结构：

```json
{{
  "mermaid": "string",
  "query": "string",
  "node_sources": [
    {{
      "node_id": "string",
      "node_text": "string",
      "rubric_criterion": {{
        "id": "string",
        "description": "string",
        "check_points": ["string"]
      }},
      "source_type": "tool_call_response | query_or_reason_or_answer | previous_mermaid",
      "source_note": "string"
    }}
  ]
}}
```

现在，输出你的最终结果：
"""

    return prompt

