"""
Reviser 第二阶段 prompt 构造器。

第二阶段目标：
- 接收 mermaid  与 trajectory；
- 根据所刻画的任务方向与 trajectory 中可挖掘信息，生成下一轮 `query`。
- `query_fuzzified` 由 fuzzify_query_prompt 单独生成。
"""

from __future__ import annotations

import json
from typing import Any, Dict, Optional

from deep_research.synthesis_v2.mermaid.mermaid import Mermaid


def build_revise_rubric_prompt(
    *,
    mermaid: str,
    traj_k: Dict[str, Any],
    metadata: Optional[Dict[str, Any]] = None,
) -> str:
    metadata = metadata or {}
    _ = metadata
    mermaid_ = Mermaid.from_str(mermaid or "").to_structure_str()
    traj_k_str = json.dumps(traj_k, ensure_ascii=False, indent=2)

    prompt = f"""
    
    
你是一个根据 mermaid  和 trajectory，以构造更有价值的 deep research 问题的助手。

你需要输出 `query`：更有价值的 deep research 问题；该 query 说明要做什么任务，以及模糊地告诉模型应该基于什么/从哪些方面/用哪些方法解决这个任务。

## 已知信息

- mermaid ：
{mermaid_}

- trajectory：
{traj_k_str}


## 你的工作流程

首先，基于 mermaid，从 trajectory 中找到与 mermaid 节点有一定关联、且可以深入挖掘的信息，并生成新的 `query`。该 query 必须是一个 deep research 研究任务，有共同的 1 个主目标。在表达上，可以是逻辑有较紧密关联（递进，深入，综合）的多个问题，但不能是多个互相独立（或者关联很弱）的问题集合。按照以下两个步骤来完成：

- 保持问题难度的同时模糊化具体信息：query 需要通过约束引导回答者沿 mermaid 的方向推进，但不要直接复述其中的节点、边、步骤顺序或解法模块，省略中间的推理路径和细节信息，只笼统的说明从哪些方面，解决什么问题。
    - 保持问题难度：
        - 不要把 trajectory 里已经需要查明的具体结果/答案当作已知前提写进去，这会导致问题难度变浅。若 trajectory 已给出某个中间结论，提问时应保留待查对象，而不是直接沿用该结论。比如 mermaid中有节点 A[查询马达加斯加和非洲大陆之间的海峡]，而 trajectory 已查明该海峡是莫桑比克海峡，那么不要提问“莫桑比克海峡在空间尺度和自然属性上有什么特点？”，而是提问“马达加斯加和非洲大陆之间的海峡有什么特点？”。
        - 如果mermaid中后续节点里有前序节点的结果，那么不要把结果当作前提写进去，而是使用前序节点隐去后续节点。比如mermaid为`A[查询2024年奥运会乒乓球男子单打冠军] --> B[查询樊振东职业生涯中的几次转折点]`，那么不要直接提问“樊振东职业生涯中有哪几次转折点？”，而是提问“2024年奥运会乒乓球男子单打冠军在职业生涯中有哪几次转折点？”
        - 不要过度简化，保留不同方面的约束：比如“分飞掠、撞击、软着陆、载人着陆等不同定义分析首次到达月球的任务是什么？”，不要过度简化为“分析首次到达月球的任务是什么？”，这些不同的方面需要保留，作为约束保证query不偏题。
        - 不要去掉起源节点（只有出边没有入边）内容中的提问对象。比如节点A[Identify the theme song of The Dukes of Hazzard]，不要简化为“Identify the theme song”，因为所有问题的起源都是通过“The Dukes of Hazzard”开始查找的。
        但是，对于非起源节点比如节点B[Search for who sings “Good Ol’ Boys.”]，其关系为[Identify the theme song of The Dukes of Hazzard]--> B[Search for who sings “Good Ol’ Boys.”]，那么B节点中的对象“Good Ol’ Boys.”应该遵循“使用前序节点隐去后续节点”的规则被隐去，简化为“Search for who sings the theme song of The Dukes of Hazzard”。
    - 省略中间的推理路径和细节信息：
        - 把具体信息，例子等变成笼统的概括，使用简单易懂的词汇：把“对比 Luna 9（99kg 着陆质量、无上升段）、Surveyor 1（单程工程验证）和 Luna 15（Apollo 11 驻留期间坠毁）的技术参数与任务结果”改写成“对比之前登月任务的技术和结果”），把“请结合推荐算法的权重配比、非内容分发环节的结构性特权，以及该用户在政府任职期间内容性质变化带来的受众重构进行综合分析”改写成“请结合推荐算法机制、结构性特权和内容变化几个方面来分析”
        - 改写成贴近普通用户表达：隐去用冗余的形容词，把“如何解释其粉丝数量能对其他头部用户形成倍数级的断层领先？”改写成“如何解释其粉丝数量能对其他头部用户形成断层领先？”。去掉具体用到的术语、书面腔、专业方法，避免“时序耦合/动态校准/跨模态/语义判别/分级验证逻辑/终局裁决准则”等学术化表达，采用朴素、简单、最普通、能直接听懂的表达。
        - mermaid 不可见：该 query 独立于 mermaid 和 trajectory，用于测试模型回答 mermaid 所刻画的任务。因此 query 里禁止使用“基于已输出/如上/上述/前文/上一轮/终版/继续上次/根据节点 A/这个电影”等指代性表述。

- 引导提问：在对 mermaid 进行模糊化提问的基础上，引导 agent 去做与 mermaid 中已有节点相关（从 trajectory 中进行挖掘），但还无法解决/没有深入探索的任务，目的是生成更有难度的 task，且希望该 task 是具体的，合理的，有意义，能被解决的。聚焦“小步深挖”，不要过度发散，仅对 trajectory 中的1-2个方面进行引导提问即可。
    - 优先引导提问trajectory中有部分答案，或者在未来能回答的问题：
        - 比如trajectory 只查明紫金矿业的竞争对手有山东黄金；不得据此提问“对比紫金矿业和山东黄金”，但是可以提问"紫金矿业的竞争对手有谁？"
        - 比如trajectory中查到了紫金矿业和山东黄金的营收情况，就可以提问"对比紫金矿业和山东黄金"，尽管营收情况只是该对比问题的部分内容，但说明了该问题是有答案的。
    - 可以往宽度、深度两方面引导提问：
        - 宽度：trajectory中出现了“能够更全面回答当前mermaid中所解决问题”的信息，那么把这个方面也写到query中，引导agent去更全面地回答这个问题。
        - 深度：trajectory中出现了“能够回答当前mermaid中没有涉及到的问题”的信息，且可以合并成一个大的deep research问题，那么把这个方面也写到query中，引导agent去更深入地回答这个问题。
    - 优先引导提问“需要证据佐证的、具体的深度分析问题”，包括但不限于：
        - 解释/验证/深入/归因/比较某个事情，比如“从病理分析脓毒症患者的治疗要快到什么程度才能够真正由危转安？”
        - 结合一些内容/从不同方面进行综合分析/推理/对比，比如“围绕 Fred 人物的完整弧线展开，结合他和弟弟的关系、与情感变化、影片在喜剧和温情之间的摇摆，以及影评对关键桥段和整体口吻的评价，深入分析《Fred Claus》的前后段为什么会形成一种很分裂的观感？"
    - 无意义的问题禁止提问：
        - 多个证据交叉核验同一个事实的问题禁止提问：“反复核验/同一事实在多个搜索/数据库重复比对并给出采信优先级/通过多个方面确认”属于浅层任务，是无意义的。
        - 不依赖证据或推理，过于自主发挥的问题禁止提问：“设计方法论/设计系统/设计机制/构建框架/输出手册”这类抽象产物导向任务，是过于自主发挥的问题，是无意义的。“这个结论有多强/是否稳定”这种程度上的量化也尽量少出现，除非 trajectory 中明确给出了量化结果。
        - 对一个简单的、公认事实的过于纠结的问题禁止提问：不要去提问一个内容为什么会出现口径差异，或者辨析同一个问题不同渠道的不同答案，或者到底那个是最权威/公认的答案，除非问题在不同的定义下发生了明显差异。例如，“哪位演员应被视为xxx的核心主演，为什么？”，“辨析电视剧和电影版本的区别”，“有哪些不同结论的第一次登上月球？如何区分？”，“定义水圈最合理的方式是什么？”，“对于哥斯达黎加有多少种动物这个问题，最精准的答案是什么？”，这些问题都是对同一个问题不同口径的过分纠结，需要重新挖掘信息改写为更有深度且有意义的问题。
    - 实事求是是第一原则：
        - query 中只能使用 trajectory 和 mermaid 中提及到且可对齐的概念，可以改变表达，但是不允许新增任何自己创造的、二者都未涉及到的主题维度或新术语、命名实体、缩写或数值规则，尽量使用已有内容中的词汇。不要提问 trajectory 中完全没有涉及的信息，也不要提问与当前 mermaid 任何节点都完全没有关系的问题。
        - 判断“是否涉及”时，以 trajectory **实际使用**为准：`tool_response` 里出现但未被 answer/reason 采纳的概念，视为未涉及；mermaid 的 Reasoning 节点所要求的分析，若 trajectory 尚无对应证据，也不得借 `query` 强行要求。
        - 严禁添加任何编造的信息：禁止引入任何没有明确规定、大众普遍认知的新命名关键词（如自造模型名、缩写、评分体系名、方法学名）。如果有大众普遍认知的术语，则必须来自 `tool_response` 原文，或 mermaid  中的节点描述。同样的，禁止包含未经过标准方法验证过（也就是可以通过查询或者搜索得到）的计算推理方法、数值、计算公式或分级阈值。
        - 不要为了深度和专业刻意进行包装：
            - 不得进行“术语升级”（把普通描述改写为更专业但未出现的术语，如把“具体步骤”改成“SOP”，把“对比”包装成“耦合分析”，把“判断真假”包装成“真伪判别模型”）
            - 不要从trajectory里的回答中引入ai命名的带引号的不明确的形容词（如“讽刺感丧失”，“贫瘠感”，“神话式历史主义”等），请使用朴素，通用的表述（如“多维风险评估”），不要创造新专有名词。

**特别注意**：如果 trajectory 没有可以挖掘的信息了，**必须**只进行模糊化而不进行引导性提问。如果 trajectory 主要是事实清单式检索、问题已经足够深入且有意义，或者再进行引导就需要变成多个并列的独立问题了，也**必须**只进行模糊化，而不进行引导性提问。宁可问题偏“查全/查清”，也不要提出 trajectory 尚未支撑的分析型 `query`。

## 输出形态（严格 JSON）：

```json
{{
  "query": "string"
}}
```

## 输出前自检
- 如果 query 中出现“基于已输出/上述/前文/上一轮/继续上次/终版”等词，必须重写为自包含版本。
- 如果 query 是对同一事实的核查/统一事实的不同口径信息的辨析/过于自主发挥的问题，必须挖掘信息改写为有意义的问题。
- 如果 query 把 trajectory 中已查明的具体结果/答案当作已知前提写进去了，必须重写为保留待查对象、隐去该结果的版本。
- 如果 query 是多个小的并列的子问题，而没有一个共同的大目标的话，必须重写为一个有大目标的 deep research 问题。
- 逐条检查 `query` 中的每个分析维度/约束方面：若无法在 trajectory 的 `tool_response` 或 answer/reason 中找到对应证据或已展开讨论，必须删除该维度；若删除后只剩事实查清类任务，则改为仅模糊化、不做引导分析。
- 若 `query` 要求综合分析/意义判断/模式归纳，但 trajectory 仅有枚举无综合，必须重写为仅覆盖 trajectory 已检索事实范围的查清型问题。

最终的输出中的内容使用英文，现在输出结果：
"""

    return prompt


def build_leaf_query_prompt(
    *,
    stage1_query: str,
    sub_mermaid: str,
    sub_rubric: Dict[str, Any],
    traj_k: Optional[Dict[str, Any]] = None,
    metadata: Optional[Dict[str, Any]] = None,
) -> str:
    """叶子拆分子图场景：保留旧接口。"""
    _ = stage1_query
    _ = sub_rubric
    return build_revise_rubric_prompt(
        mermaid=sub_mermaid,
        traj_k=traj_k or {},
        metadata=metadata,
    )
